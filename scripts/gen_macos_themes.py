def convert(src, mapping, glob, out, title):
    text = (root / src).read_text(encoding='utf-8')
    def recolor(m):
        v = m.group(2).upper()
        return f'{m.group(1)}="{mapping.get(v, v)}"'
    text = re.sub(r'(fgColor|bgColor)="([0-9A-Fa-f]{6})"', recolor, text)
    def fix_global(m):
        tag = m.group(0)
        name = re.search(r'name="([^"]*)"', tag).group(1)
        if name not in glob: return tag
        fg, bg = glob[name]
        if fg: tag = re.sub(r'fgColor="[0-9A-Fa-f]*"', f'fgColor="{fg}"', tag) if 'fgColor=' in tag else tag.replace(' styleID', f' fgColor="{fg}" styleID', 1)
        if bg: tag = re.sub(r'bgColor="[0-9A-Fa-f]*"', f'bgColor="{bg}"', tag) if 'bgColor=' in tag else tag.replace(' styleID', f' bgColor="{bg}" styleID', 1)
        if name == 'Default Style': tag = re.sub(r'fontName="[^"]*"', 'fontName="Menlo"', re.sub(r'fontSize="[^"]*"', 'fontSize="12"', tag))
        return tag
    text = re.sub(r'<WidgetStyle [^>]*>', fix_global, text)
    text = re.sub(r'<\?xml[^>]*\?>', '<?xml version="1.0" encoding="UTF-8" ?>\n<!-- ' + title + ' — generated by scripts/gen_macos_themes.py -->', text, count=1)
    (root / 'themes' / out).write_text(text, encoding='utf-8')
    print('wrote', out)

convert('stylers.model.xml', LIGHT, LIGHT_GLOBAL, 'macOS Light.xml', 'macOS Light: an Xcode-like light theme')
convert('themes/DarkModeDefault.xml', DARK, DARK_GLOBAL, 'macOS Dark.xml', 'macOS Dark: an Xcode-like dark theme')
