#!/usr/bin/env python3
"""Generate src/generated/ScintillaCocoaKeyMap.inc: Scintilla's built-in macOS key map (KeyMap::MapDefault with
OS_X_KEYS = 1) as plain numbers, so Textpad++ can restore a native binding after it re-assigns a key.
Usage: python3 -I scripts/gen_scintilla_keymap.py ."""
import pathlib, re, sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.')
src = (root / 'third_party/scintilla/src/KeyMap.cxx').read_text(encoding='utf-8')
body = src[src.index('const KeyToCommand KeyMap::MapDefault[] = {'):]
body = body[:body.index('\n};')]
# resolve #if OS_X_KEYS / #else / #endif with OS_X_KEYS = 1
out_lines, stack = [], []
for line in body.splitlines():
    s = line.strip()
    if s.startswith('#if'):
        stack.append('OS_X_KEYS' in s and '!' not in s)
        continue
    if s.startswith('#else'):
        stack[-1] = not stack[-1]
        continue
    if s.startswith('#endif'):
        stack.pop()
        continue
    if all(stack):
        out_lines.append(line)
mods = {'SCI_NORM': '0', 'SCI_SHIFT': 'SCMOD_SHIFT', 'SCI_CTRL': 'SCMOD_CTRL', 'SCI_ALT': 'SCMOD_ALT', 'SCI_META': 'SCMOD_META',
        'SCI_CSHIFT': '(SCMOD_CTRL | SCMOD_SHIFT)', 'SCI_ASHIFT': '(SCMOD_ALT | SCMOD_SHIFT)', 'SCI_CTRL_META': 'SCMOD_META',
        'SCI_SCTRL_META': '(SCMOD_META | SCMOD_SHIFT)'}
rows = []
for m in re.finditer(r"\{\s*(Keys::\w+|Key\('(.)'\)|Key\(0\))\s*,\s*(\w+)\s*,\s*(Message::\w+|static_cast<Message>\(0\))\s*\}", '\n'.join(out_lines)):
    key, ch, mod, msg = m.group(1), m.group(2), m.group(3), m.group(4)
    if key == 'Key(0)':
        continue
    k = "'%s'" % ch.replace("'", "\\'").replace('\\', '\\\\') if ch else 'SCK_' + key.split('::')[1].upper()
    sci = 'SCI_' + msg.split('::')[1].upper()
    rows.append('{%s, %s, %s},' % (k, mods[mod], sci))
hdr = ['// GENERATED by scripts/gen_scintilla_keymap.py from third_party/scintilla/src/KeyMap.cxx (OS_X_KEYS = 1).',
       '// Scintilla License (see third_party/scintilla/License.txt). Do not edit by hand.',
       '// {key, modifiers, message}']
(root / 'src/generated/ScintillaCocoaKeyMap.inc').write_text('\n'.join(hdr + rows) + '\n', encoding='utf-8')
print('ScintillaCocoaKeyMap.inc rows=%d' % len(rows))
